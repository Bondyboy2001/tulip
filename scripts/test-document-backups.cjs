const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { backupVault } = require('../electron/vault-backup')
const { documentBackups } = require('../electron/document-backups')
;(async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tulip-document-backups-'))
  try {
    const vault = path.join(root, 'vault'), backup = path.join(root, 'backup')
    await fs.mkdir(vault)
    await fs.writeFile(path.join(vault, 'Note.md'), 'original')
    await backupVault(vault, backup)
    const api = documentBackups({ settings: () => ({ lastPath: backup, lastSuccess: 1 }), getVault: () => vault, realSafeTargetPath: async rel => path.join(vault, rel) })
    assert.equal((await api.list(null, 'Note.md'))[0].available, true)
    assert.equal((await api.list(null, 'Missing.md'))[0].available, false)
    await fs.writeFile(path.join(vault, 'Note.md'), 'newer')
    assert.equal(await api.preview(null, backup, 'Note.md'), 'original')
    const restored = await api.restore(null, backup, 'Note.md')
    assert.equal(await fs.readFile(path.join(vault, restored.path), 'utf8'), 'original')
    assert.equal(await fs.readFile(path.join(vault, 'Note.md'), 'utf8'), 'newer')
    await assert.rejects(api.preview(null, root, 'Note.md'), /no longer recorded/)
    await assert.rejects(api.list(null, '../Note.md'), /Invalid document/)
    await fs.writeFile(path.join(backup, 'Note.md'), 'corrupt')
    await assert.rejects(api.restore(null, backup, 'Note.md'), /integrity/)
    if (process.platform !== 'win32') {
      await fs.unlink(path.join(backup, 'Note.md'))
      await fs.symlink(path.join(vault, 'Note.md'), path.join(backup, 'Note.md'))
      await assert.rejects(api.preview(null, backup, 'Note.md'), /outside/)
    }
    await fs.rm(backup, { recursive: true })
    assert.ok((await api.list(null, 'Note.md'))[0].error)
    console.log('ok - backup preview, separate-copy restore, corruption, missing/offline backups and path boundaries')
  } finally { await fs.rm(root, { recursive: true, force: true }) }
})().catch(error => { console.error(error); process.exitCode = 1 })
